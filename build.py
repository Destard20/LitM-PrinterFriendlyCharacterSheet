#!/usr/bin/env python3
"""Build every sheet, in every language, from the templates in src/.

    python3 build.py            # HTML only
    python3 build.py --pdf      # HTML, then the PDFs whose HTML changed
    python3 build.py --pdf-all  # HTML, then every PDF

Templates (src/*.html) contain {{key}} placeholders. Text keys come from the
language files in src/lang/<language>.json; layout keys (paper size, cut lines,
...) are filled in by this script. Each language gets its own output folder
(en/, it/, ...), named after its JSON file.

To add a language: copy src/lang/en.json to src/lang/<code>.json, translate the
values (keep the keys), and run this script again.

PDFs are printed with a headless Chromium-based browser (Chrome, Edge, Chromium
or Brave); set LITM_BROWSER to the browser's path to choose one yourself. If none
is found, Firefox is used instead, through geckodriver.
pdf-manifest.json remembers which HTML each PDF was printed from, so only PDFs
whose HTML changed are printed again.

Only the Python standard library is used.
"""
import argparse
import base64
import functools
import hashlib
import json
import os
import re
import shutil
import signal
import socket
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
LANG_DIR = SRC / "lang"
FONTS_DIR = SRC / "fonts"
MANIFEST = ROOT / "pdf-manifest.json"
PLACEHOLDER = re.compile(r"\{\{(\w+)\}\}")

SCRATCH = '<span class="claw-scratch">彡</span>'
NO_SCRATCH_PDF = "No Scratchmarks"

# Action cards: standard trading card size, 3 x 3 per page, edge to edge.
CARD_W, CARD_H = 63.0, 88.0
CARD_PAD = 1.5  # gap between the cut line and the card border, mm
PAPERS = {
    "A4": {"page_size": "A4", "w": 210.0, "h": 297.0},
    "Letter": {"page_size": "letter", "w": 215.9, "h": 279.4},
}
# Character sheet: minimum height of a writing line, in px. Letter paper is 17.6 mm shorter
# than A4, so its lines are a little closer together for everything to fit.
LINE_H = {"A4": 19, "Letter": 16}

PDF_TIMEOUT = 120  # seconds per PDF


class BuildError(Exception):
    pass


WRITTEN: set = set()  # every HTML file written in this run


# ---------------------------------------------------------------------------
# HTML
# ---------------------------------------------------------------------------

def mm(x: float) -> str:
    """Format a millimetre value without trailing zeros (10.50 -> 10.5)."""
    return f"{x:.2f}".rstrip("0").rstrip(".")


@functools.lru_cache(maxsize=None)
def font_faces() -> str:
    """@font-face rules with the fonts from src/fonts/ embedded, so every OS shows the same fonts."""
    faces = json.loads((FONTS_DIR / "fonts.json").read_text(encoding="utf-8"))
    rules = []
    for face in faces:
        data = base64.b64encode((FONTS_DIR / face["file"]).read_bytes()).decode("ascii")
        rules.append(
            f"    @font-face {{ font-family: '{face['family']}'; font-style: {face['style']}; "
            f"font-weight: {face['weight']}; font-display: block; "
            f"unicode-range: {face['unicode_range']}; "
            f"src: url(data:font/woff2;base64,{data}) format('woff2'); }}"
        )
    return "\n".join(rules)


def render(template: str, values: dict, used: set) -> str:
    """Fill {{key}} placeholders in src/<template>. Unknown keys are an error."""
    text = (SRC / template).read_text(encoding="utf-8")
    values = {"font_faces": font_faces(), **values}

    def fill(m):
        key = m.group(1)
        if key not in values:
            raise BuildError(f"{template}: no value for {{{{{key}}}}}")
        used.add(key)
        return values[key]

    return PLACEHOLDER.sub(fill, text)


def write(path: Path, html: str, template: str) -> None:
    """Write a generated page, with a note saying where it comes from."""
    note = f"<!-- Generated by build.py from src/{template}. Edit the template, then run: python3 build.py -->"
    first, rest = html.split("\n", 1)  # keep <!DOCTYPE html> as the very first line
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{first}\n{note}\n{rest}", encoding="utf-8", newline="\n")
    WRITTEN.add(path)
    print("  wrote", rel(path))


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def build_hero_sheets(html_dir: Path, pdf_dir: Path, code: str, text: dict, used: set) -> list:
    """Write the character sheets; return the (html, pdf, paper) to print."""
    to_print = []
    for paper, p in PAPERS.items():
        page = {"page_size": p["page_size"], "paper_w": mm(p["w"]), "paper_h": mm(p["h"]),
                "line_h": str(LINE_H[paper]), "line_pitch": str(LINE_H[paper] + 6)}  # + margin and border
        for suffix, scratch, pdf_suffix in (("", SCRATCH, ""), ("_NoScratchmarks", "", f", {NO_SCRATCH_PDF}")):
            html = render("hero_sheet.html", {**text, **page, "scratch": scratch}, used)
            html_path = html_dir / f"LitM_HeroSheet_{code}_{paper}{suffix}.html"
            write(html_path, html, "hero_sheet.html")
            to_print.append((html_path, pdf_dir / f"{text['title_sheet']} ({paper}{pdf_suffix}).pdf", paper))
        html = render("hero_sheet_web.html", {**text, **page}, used)
        write(html_dir / f"LitM_WebFillable_HeroSheet_{code}_{paper}.html", html, "hero_sheet_web.html")
    return to_print


def cut_lines(grid_x: float, grid_y: float) -> str:
    """Dashed lines across the whole page, on every card edge."""
    lines = [f'    <div class="cut v" style="left: {mm(grid_x + i * CARD_W)}mm;"></div>' for i in range(4)]
    lines += [f'    <div class="cut h" style="top: {mm(grid_y + i * CARD_H)}mm;"></div>' for i in range(4)]
    return "\n".join(lines)


def build_action_cards(html_dir: Path, pdf_dir: Path, code: str, text: dict, used: set) -> list:
    """Write the action card pages; return the (html, pdf, paper) to print."""
    to_print = []
    web_css = (SRC / "action_card_web.css").read_text(encoding="utf-8").rstrip("\n")
    # (card template, scratchmark, file prefix, file suffix, page title key, extra CSS, PDF name suffix or None)
    variants = [
        ("action_card.html", SCRATCH, "LitM_ActionCards", "", "title_cards", "", ""),
        ("action_card.html", "", "LitM_ActionCards", "_NoScratchmarks", "title_cards", "", f", {NO_SCRATCH_PDF}"),
        ("action_card_web.html", "", "LitM_WebFillable_ActionCards", "", "title_cards_web", web_css + "\n", None),
    ]
    used.add("title_cards")  # used for the PDF names
    for card_template, scratch, prefix, suffix, title_key, extra_css, pdf_suffix in variants:
        card = render(card_template, {**text, "scratch": scratch}, used).rstrip("\n")
        cards = "\n".join([card] * 9)
        used.add(title_key)
        for paper, p in PAPERS.items():
            grid_x = (p["w"] - 3 * CARD_W) / 2
            grid_y = (p["h"] - 3 * CARD_H) / 2
            layout = {
                "page_title": text[title_key],
                "web_css": extra_css,
                "paper_name": paper,
                "page_size": p["page_size"],
                "paper_w": mm(p["w"]),
                "paper_h": mm(p["h"]),
                "grid_x": mm(grid_x),
                "grid_y": mm(grid_y),
                "card_w": mm(CARD_W),
                "card_h": mm(CARD_H),
                "card_pad": mm(CARD_PAD),
                "cut_lines": cut_lines(grid_x, grid_y),
                "cards": cards,
            }
            html = render("action_cards.html", {**text, **layout}, used)
            html_path = html_dir / f"{prefix}_{code}_{paper}{suffix}.html"
            write(html_path, html, "action_cards.html")
            if pdf_suffix is not None:
                to_print.append((html_path, pdf_dir / f"{text['title_cards']} ({paper}{pdf_suffix}).pdf", paper))
    return to_print


# Fellowship card: the quest box and the two side boxes are ruled with more lines than fit;
# each box clips the extra ones, so the lines always fill the box whatever its height.
RULED_LINES = '<div class="line"></div>' * 30


def build_fellowship(html_dir: Path, pdf_dir: Path, code: str, text: dict, used: set) -> list:
    """Write the Fellowship card sheets; return the (html, pdf, paper) to print.

    Full page: one card per sheet. Half page: the same card at half size, twice per sheet."""
    to_print = []
    used.update({"title_fellowship", "title_fellowship_web", "two_per_page"})  # PDF names, page titles
    title = text["title_fellowship"]
    web_css = (SRC / "fellowship_web.css").read_text(encoding="utf-8")
    for paper, p in PAPERS.items():
        page = {"page_title": title, "page_size": p["page_size"], "paper_name": paper,
                "paper_w": mm(p["w"]), "paper_h": mm(p["h"])}
        for layout, file_suffix, pdf_part in (("full", "", ""), ("half", "_2PerPage", f", {text['two_per_page']}")):
            for scratch_suffix, scratch, pdf_scratch in (("", SCRATCH, ""), ("_NoScratchmarks", "", f", {NO_SCRATCH_PDF}")):
                spread = render("fellowship_spread.html",
                                {**text, "scratch": scratch, "ruled_lines": RULED_LINES}, used).rstrip("\n")
                region = f'        <div class="region">\n{spread}\n        </div>\n'
                if layout == "full":
                    body = region
                else:  # two copies, with a cut line across the middle of the sheet
                    half = mm(p["h"] / 2)
                    body = (region
                            + f'        <div class="cut h" style="top: {half}mm;"></div>\n'
                            + f'        <div class="cut-hint" style="top: {half}mm;"><span class="scissors">✂</span>{text["cut_hint"]}</div>\n'
                            + region)
                pages = f'    <div class="page">\n{body}    </div>'
                html = render("fellowship.html", {**text, **page, "layout": layout, "pages": pages, "web_css": ""}, used)
                html_path = html_dir / f"LitM_Fellowship_{code}_{paper}{file_suffix}{scratch_suffix}.html"
                write(html_path, html, "fellowship.html")
                to_print.append((html_path, pdf_dir / f"{title} ({paper}{pdf_part}{pdf_scratch}).pdf", paper))
        # Web-fillable: full page only (no PDF; it is printed after filling it in)
        spread = render("fellowship_web_spread.html", {**text, "ruled_lines": RULED_LINES}, used).rstrip("\n")
        pages = f'    <div class="page">\n        <div class="region">\n{spread}\n        </div>\n    </div>'
        html = render("fellowship.html", {**text, **page, "page_title": text["title_fellowship_web"],
                                          "layout": "full", "pages": pages, "web_css": web_css}, used)
        write(html_dir / f"LitM_WebFillable_Fellowship_{code}_{paper}.html", html, "fellowship.html")
    return to_print


def build_language(lang_file: Path) -> list:
    data = json.loads(lang_file.read_text(encoding="utf-8"))
    meta = {k: v for k, v in data.items() if k.startswith("_")}
    text = {k: v for k, v in data.items() if not k.startswith("_")}
    for key in ("_code", "_folder_sheet", "_folder_cards", "_folder_fellowship"):
        if key not in meta:
            raise BuildError(f"{lang_file.name}: missing {key}")

    out = ROOT / lang_file.stem
    code = meta["_code"]
    print(f"{lang_file.name} -> {out.name}/")
    used: set = set()
    sheet, cards = meta["_folder_sheet"], meta["_folder_cards"]
    to_print = build_hero_sheets(out / "HTML" / sheet, out / "PDF" / sheet, code, text, used)
    to_print += build_action_cards(out / "HTML" / cards, out / "PDF" / cards, code, text, used)
    fellowship = meta["_folder_fellowship"]
    to_print += build_fellowship(out / "HTML" / fellowship, out / "PDF" / fellowship, code, text, used)

    unused = sorted(set(text) - used)
    if unused:
        print(f"  warning: {lang_file.name} has keys no template uses: {', '.join(unused)}")
    return to_print


def warn_stale(lang_files: list, to_print: list) -> None:
    """Point out HTML/PDF files in the output folders that this build didn't produce."""
    expected = WRITTEN | {pdf for _, pdf, _ in to_print}
    for lang_file in lang_files:
        out = ROOT / lang_file.stem
        for path in sorted(out.rglob("*")):
            if path.suffix in (".html", ".pdf") and path not in expected:
                print(f"warning: {rel(path)} is not produced by build.py any more; delete it if it's left over")


